export function translateText(text: string, locale: Locale) {
  return locale === 'am' ? amharic[text] || text : text
}

type LanguageContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (value: string) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocale] = useState<Locale>('en')

  useEffect(() => {
    const saved = window.localStorage.getItem('dental-erp-locale') as Locale | null
    // Hydrate with the server's English snapshot, then restore the preference.
    // eslint-disable-next-line react-hooks/set-state-in-effect
    if (saved === 'am') setLocale('am')
  }, [])

  useEffect(() => {
    window.localStorage.setItem('dental-erp-locale', locale)
    document.documentElement.lang = locale
  }, [locale])

  const value = useMemo(
    () => ({
      locale,
      setLocale,
      t: (text: string) => translateText(text, locale),
    }),
    [locale]
  )

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const value = useContext(LanguageContext)
  if (!value) throw new Error('useLanguage must be used inside LanguageProvider')
  return value
}
